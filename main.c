#include <stdio.h>
#include <locale.h>

/*
КОНТРОЛЬНЫЕ ПРИМЕРЫ ДЛЯ ПРОВЕРКИ АЛГОРИТМА:
Тест 1 (Базовый): V1=2, t1=20; V2=3, t2=45; V3=5, t3=80  -> Ответ: V=10, t=57.50
Тест 2 (Равные t): V1=2, t1=25; V2=3, t2=25; V3=5, t3=25 -> Ответ: V=10, t=25.00
Тест 3 (Дисбаланс): V1=1, t1=10; V2=1, t2=10; V3=1000, t3=90 -> Ответ: V=1002, t=89.84
*/

int main() {
    // Для смены теста просто подставляй сюда числа из таблицы выше
    int V1 = 2;
    int t1 = 20;

    int V2 = 3;
    int t2 = 45;

    int V3 = 5;
    int t3 = 80;

    setlocale(LC_ALL, "Russian");

    int V_total = V1 + V2 + V3;
    int total_heat = (V1 * t1) + (V2 * t2) + (V3 * t3);
    float t_final = (float)total_heat / V_total;

    printf("РАСЧЕТ СМЕШИВАНИЯ ВОДЫ В СОСУДАХ\n");
    printf("================================\n\n");

    printf("УСЛОВИЯ:\n");
    printf("- Сосуд 1: объем = %d л., температура = %d C.\n", V1, t1);
    printf("- Сосуд 2: объем = %d л., температура = %d C.\n", V2, t2);
    printf("- Сосуд 3: объем = %d л., температура = %d C.\n", V3, t3);
    printf("- Действие: воду из трех сосудов слили в один общий сосуд.\n\n");

    printf("РАСЧЕТ:\n");
    printf("- Общий объем смеси: %d л + %d л + %d л = %d литров.\n", V1, V2, V3, V_total);
    printf("- Суммарный тепловой баланс: (%d*%d) + (%d*%d) + (%d*%d) = %d ед.\n", V1, t1, V2, t2, V3, t3, total_heat);
    printf("- Итоговая температура: %d ед. теплоты / %d л. объема = %.2f C.\n", total_heat, V_total, t_final);
    printf("================================\n");

    printf("РЕЗУЛЬТАТ: В новом сосуде содержится %d л. воды с температурой %.2f C.\n", V_total, t_final);

    return 0;
}
